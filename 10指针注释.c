#include <stdio.h> // 引入标准输入输出库，为了使用 printf 函数

int main() {
    // 1. 定义一个普通的整型变量 a，并把数字 42 存进去
    int a = 42;               // 数字 42 躺在名为 a 的柜子里

    // 2. 打印变量 a 里面装的值（也就是 42）
    // %d 是整数的占位符，\n 表示换行
    printf("a 的值 = %d\n", a);

    // 3. 打印变量 a 在内存中的地址（也就是柜子的门牌号）
    // & 是“取地址符”，&a 就拿到了 a 的地址
    // %p 是专门用来打印内存地址的占位符
    // (void*) 是强制类型转换，因为 printf 的 %p 要求参数必须是 void* 类型的指针
    printf("a 的地址 = %p\n", (void*)&a);   // &a 就是"a 所在柜子的编号"

    // 4. 定义一个指针变量 p，用来专门存放内存地址
    // int *p 声明 p 是一个指向整型的指针
    // &a 把 a 的地址赋值给了 p，现在 p 指向了 a
    int *p = &a;              // 纸条 p 上写着"a 的地址"

    // 5. 打印指针变量 p 里存的地址值
    // 注意：打印的是 p 的值（也就是 a 的地址），不是 *p
    printf("p 里存的是 a 的地址：%p\n", (void*)p);

    // 6. 使用“解引用符” * 来获取指针指向的值
    // *p 的意思是：“顺着 p 存的地址，找到那个柜子，拿出里面的东西”
    printf("*p 就是通过纸条找到的值：%d\n", *p);  // *p = a = 42

    // 7. 通过指针修改原变量的值
    // *p = 100 的意思是：“找到 p 指向的那个柜子，把里面的东西换成 100”
    *p = 100;                 // 通过纸条改柜子里的内容

    // 8. 验证 a 的值是否被修改
    // 因为 p 指向 a，所以通过 *p 修改，实际上就是修改了 a 本身
    printf("改完之后 a = %d\n", a);   // a 变成 100 了！
    
    return 0; // 程序正常退出
}
